// Writes src/lib/connector-icons.ts: the logo of each connector in the
// catalog that the Simple Icons set carries (https://simpleicons.org, CC0).
// The marks are trademarks of their owners and are shown only to name the
// product a connector is for. Run after changing the catalog:
//
//   node scripts/build-connector-icons.mjs
import { readFile, writeFile } from "node:fs/promises";

import * as icons from "simple-icons";

const catalog = await readFile(
  new URL("../src/lib/connectors.ts", import.meta.url),
  "utf8",
);
const entries = [...catalog.matchAll(/id: "([^"]+)",\s+name: "([^"]+)"/g)].map(
  ([, id, name]) => ({ id, name }),
);

// Where the catalog's name is not the icon's title.
const ALIAS = {
  "GitHub Issues": "GitHub",
  "GitHub Advanced Security": "GitHub",
  "GitHub Copilot coding agent": "GitHub Copilot",
  "GitLab Issues": "GitLab",
  "GitLab CI": "GitLab",
  "Azure DevOps Boards": "Azure DevOps",
  "Azure Repos": "Azure DevOps",
  "Azure Pipelines": "Azure Pipelines",
  "Notion Docs": "Notion",
  "Jira Service Management": "Jira",
  "Cursor background agents": "Cursor",
  "Claude Code": "Claude",
  "Salesforce Service Cloud": "Salesforce",
  "Figma FigJam": "Figma",
  "Google Docs": "Google Docs",
  "Terraform Cloud": "Terraform",
  "Perforce Helix": "Perforce",
  "Splunk On-Call": "Splunk",
  "Apollo GraphOS": "Apollo GraphQL",
  Kafka: "Apache Kafka",
  BigQuery: "Google BigQuery",
  SonarQube: "SonarQube Server",
  YouTrack: "JetBrains",
  "Zoho Projects": "Zoho",
  "Argo CD": "Argo",
  "Dropbox Paper": "Dropbox",
  Lucidchart: "Lucid",
  SwaggerHub: "Swagger",
};
const SKIP = new Set([
  "Email",
  "Factory",
  "Height",
  "Plane",
  "Front",
  "Outline",
]);

const byTitle = new Map(
  Object.values(icons)
    .filter((icon) => icon && typeof icon === "object" && icon.title)
    .map((icon) => [icon.title.toLowerCase(), icon]),
);

// How bright a brand colour is, so a near-black mark can be shown in the
// text colour on a dark ground, and a near-white one on a light ground.
function toneOf(hex) {
  const [r, g, b] = [0, 2, 4].map((at) => parseInt(hex.slice(at, at + 2), 16));
  const light = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  return light < 0.22 ? "dark" : light > 0.82 ? "light" : "mid";
}

const found = [];
const missing = [];
for (const { id, name } of entries) {
  const icon = SKIP.has(name)
    ? undefined
    : byTitle.get((ALIAS[name] ?? name).toLowerCase());
  if (icon) {
    found.push(
      `  "${id}": { hex: "#${icon.hex}", tone: "${toneOf(icon.hex)}", path: "${icon.path}" },`,
    );
  } else missing.push(name);
}

await writeFile(
  new URL("../src/lib/connector-icons.ts", import.meta.url),
  `// Generated by scripts/build-connector-icons.mjs. Do not edit by hand.
// Logos from Simple Icons (CC0): one path on a 24 by 24 grid, with the
// brand's colour. "tone" says whether that colour is too dark or too light
// to show on a ground of the same kind. The marks are trademarks of their
// owners, shown only to name the product.
export interface ConnectorIcon {
  hex: string;
  tone: "dark" | "mid" | "light";
  path: string;
}

export const CONNECTOR_ICONS: Record<string, ConnectorIcon> = {
${found.join("\n")}
};
`,
);
